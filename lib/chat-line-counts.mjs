const unknown=()=>({total:null,technical:null,ordinary:null});
const tests=path=>/(^|\/)(?:tests?|__tests__|uitests|unittests|тесты)(?:\/|$)|[._-](?:tests?|specs?)\.[^/]+$/i.test(path)||/(?:Test|Tests|Spec|Specs)\.[^/]+$/.test(path);
const generated=path=>/(^|\/)(?:generated|__generated__|autogenerated)(?:\/|$)|\.(?:Section)?Generated\.swift$/i.test(path);

function fileKind(change) {
  if(change.generated_file===true)return 'technical';
  const path=change.new_path||change.old_path;
  if(typeof path!=='string'||!path)return 'unknown';
  if(tests(path)||generated(path)||!/\.(?:swift|ya?ml)$/i.test(path))return 'technical';
  return /\.swift$/i.test(path)?'swift':'yaml';
}

function commentOnly(content,state,kind) {
  const text=content.trim();
  if(!text)return true;
  if(kind==='yaml')return text.startsWith('#');
  if(!state.depth&&!text.startsWith('/*'))return text.startsWith('//');
  let cursor=0;
  while(cursor<text.length) {
    if(state.depth) {
      const next=/\/\*|\*\//g;next.lastIndex=cursor;
      const token=next.exec(text);
      if(!token)return true;
      state.depth+=token[0]==='/*'?1:-1;cursor=token.index+2;
    }else {
      while(/\s/.test(text[cursor]||'')&&cursor<text.length)cursor++;
      if(cursor>=text.length||text.startsWith('//',cursor))return true;
      if(!text.startsWith('/*',cursor))return false;
      state.depth++;cursor+=2;
    }
  }
  return true;
}

export function lineCounts(diffs) {
  if(!Array.isArray(diffs)||diffs.some(change=>!change||change.too_large||change.collapsed||change.overflow||change.truncated||typeof change.diff!=='string'))return unknown();
  let total=0,technical=0,classificationKnown=true;
  for(const change of diffs) {
    const kind=fileKind(change),state={depth:0};let hunk=false;
    for(const row of change.diff.split('\n')) {
      if(row.startsWith('@@')) {hunk=true;state.depth=0;continue;}
      if(row.startsWith(' ')&&['swift','yaml'].includes(kind))commentOnly(row.slice(1),state,kind);
      if(!row.startsWith('+')||!hunk&&/^\+\+\+ (?:[ab]\/|\/dev\/null)/.test(row))continue;
      total++;
      if(kind==='technical')technical++;
      else if(kind==='unknown')classificationKnown=false;
      else if(commentOnly(row.slice(1),state,kind))technical++;
    }
  }
  return {total,technical:classificationKnown?technical:null,ordinary:classificationKnown?total-technical:null};
}
